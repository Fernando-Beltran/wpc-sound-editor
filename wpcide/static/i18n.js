const LANG_KEY = "wpcide.lang";

function pickLanguage() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && STRINGS[saved]) return saved;
  } catch (ignored) { /* private mode */ }
  return (navigator.language || "es").toLowerCase().startsWith("en") ? "en" : "es";
}

let lang = pickLanguage();

function t(key, values) {
  const table = STRINGS[lang] || STRINGS.es;
  let text = table[key];
  if (text === undefined) text = STRINGS.es[key];
  if (text === undefined) return key;
  if (values) {
    for (const [name, value] of Object.entries(values)) {
      text = text.split(`{${name}}`).join(value);
    }
  }
  return text;
}

function setLanguage(next) {
  lang = STRINGS[next] ? next : "es";
  try { localStorage.setItem(LANG_KEY, lang); } catch (ignored) { /* private mode */ }
  document.documentElement.lang = lang;

  const flag = document.getElementById("flag");
  if (flag) {
    // Built from code points rather than pasted in: the flags are
    // surrogate pairs, and this file stays plain ASCII where it can.
    // The flag shows the language the button switches *to*, as its
    // label does.
    const pair = lang === "es" ? [0x1F1EC, 0x1F1E7] : [0x1F1EA, 0x1F1F8];
    flag.textContent = String.fromCodePoint(pair[0], pair[1]);
  }
  applyStatic();
}

/** Fills in everything the markup labelled, so it can switch live. */
function applyStatic() {
  for (const node of document.querySelectorAll("[data-i18n]")) {
    node.textContent = t(node.dataset.i18n);
  }
  for (const node of document.querySelectorAll("[data-i18n-ph]")) {
    node.placeholder = t(node.dataset.i18nPh);
  }
  for (const node of document.querySelectorAll("[data-i18n-title]")) {
    node.title = t(node.dataset.i18nTitle);
  }
  document.title = t("app.title") + " WPC";
}
